package net.paperstream.paperproxy.bungee.layer;

import com.velocitypowered.api.proxy.messages.ChannelIdentifier;
import com.velocitypowered.api.proxy.messages.LegacyChannelIdentifier;
import com.velocitypowered.api.proxy.messages.MinecraftChannelIdentifier;

/**
 * Bungee names plugin channels with plain strings; Velocity uses identifiers.
 */
final class Channels {

  private Channels() {
    throw new AssertionError();
  }

  static ChannelIdentifier identifier(final String channel) {
    if (channel.indexOf(':') > 0) {
      return MinecraftChannelIdentifier.from(channel);
    }
    return new LegacyChannelIdentifier(channel);
  }
}
